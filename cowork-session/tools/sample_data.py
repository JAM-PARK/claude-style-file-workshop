def quote_year_total(q):
    """1년 실질 비용 (VAT 포함, 원 단위)."""
    total = 0
    for _, amount, vat_in in q['year']:
        total += amount if vat_in else round(amount * 1.1)
    return total


def quote_headline(q):
    """견적서 첫 장에 크게 보이는 금액."""
    return sum(a for _, a in q['lines'])


